Page({
  data: {
    type: 'privacy', // privacy | terms
    title: '',
    content: '',
  },
  onLoad(options) {
    const type = options.type || 'privacy';
    this.setData({ type });
    if (type === 'privacy') {
      wx.setNavigationBarTitle({ title: '隐私政策' });
      this.setData({
        title: '隐私政策',
        content: PRIVACY_CONTENT,
      });
    } else {
      wx.setNavigationBarTitle({ title: '用户协议' });
      this.setData({
        title: '用户协议',
        content: TERMS_CONTENT,
      });
    }
  },
});

